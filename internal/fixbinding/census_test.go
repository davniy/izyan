func TestLinkedAliasBypassCannotDisappearFromCover(t *testing.T) {
	forms := map[string]string{
		"ordinary":          "p := cfg.Root; os.MkdirAll(p, 0711)",
		"chain":             "p := cfg.Root; q := p; os.MkdirAll(q, 0711)",
		"assignment":        "var p string; p = cfg.Root; os.MkdirAll(p, 0711)",
		"declaration":       "var p = cfg.Root; os.MkdirAll(p, 0711)",
		"branch_join":       "p := cfg.Root; if choose { p = cfg.State }; os.MkdirAll(p, 0711)",
		"forward_parameter": "p := cfg.Root; forward(p)",
		"forward_return":    "p := identity(cfg.Root); os.MkdirAll(p, 0711)",
	}
	for name, body := range forms {
		t.Run(name, func(t *testing.T) {
			files := map[string][]byte{
				"absent/operation.go": []byte(`package absent
import "os"
import "example.com/dep/config"
func Direct(cfg *config.Config) { os.MkdirAll(cfg.Root, 0711) }
`),
				"linked/bypass.go": []byte(`package linked
import "os"
import "example.com/dep/config"
func Bypass(cfg *config.Config, choose bool) { ` + body + ` }
func forward(p string) { os.MkdirAll(p, 0711) }
func identity(p string) string { return p }
`),
				"config/config.go": []byte("package config\ntype Config struct { Root, State string }\n"),
			}
			c, err := CensusSource(CensusOptions{Module: ModuleIdentity{Path: "example.com/dep", Version: "v1.0.0"}, Files: files})
			if err != nil {
				t.Fatal(err)
			}
			found := false
			blocked := false
			for _, op := range c.Operations {
				if op.Declaration.Name == "Bypass" {
					found = true
					if !op.Entry {
						t.Fatal("exported bypass lost direct-entry provenance")
					}
				}
			}
			for _, ob := range c.Obligations {
				if ob.Declaration.Name == "Bypass" {
					blocked = true
				}
			}
			if !found && !blocked {
				t.Fatalf("linked bypass vanished: %+v", c)
			}
			if !found {
				t.Fatalf("supported alias form %s did not enumerate Bypass: %+v", name, c.Obligations)
			}
			directKey := ""
			for _, op := range c.Operations {
				if op.Declaration.Name == "Direct" {
					directKey = op.Key
				}
			}
			if directKey == "" {
				t.Fatal("absent direct operation was not inventoried")
			}
			linked := false
			for _, op := range c.Subjects(directKey).Subjects {
				if op.Declaration.Name == "Bypass" {
					linked = true
				}
			}
			if !linked {
				t.Fatal("linked bypass failed to join the same resource candidate space")
			}
			if !found && c.Analysis.Complete {
				t.Fatal("unsupported propagation certified analysis complete")
			}
			if c.Cover.Complete {
				t.Fatal("a census cannot certify a necessary cover")
			}
		})
	}
}

func TestUnsupportedPropagationBlocksCompletion(t *testing.T) {
	forms := map[string]string{
		"unknown":            "unknown(cfg.Root)",
		"pointer":            "p := &cfg.Root; *p = cfg.State",
		"interface":          "var p any = cfg.Root; _ = p",
		"structure":          "p := []string{cfg.Root}; _ = p",
		"map":                "p := map[string]string{\"x\": cfg.Root}; _ = p",
		"closure":            "p := func() { os.MkdirAll(cfg.Root, 0711) }; _ = p",
		"return":             "return cfg.Root",
		"global_constructor": "unknown()",
	}
	for name, body := range forms {
		t.Run(name, func(t *testing.T) {
			result := ""
			if name == "return" {
				result = "string"
			}
			raw := []byte("package p\nimport \"os\"\ntype Config struct { Root, State string }\nfunc Bypass(cfg *Config) " + result + " { " + body + " }\n")
			c, err := CensusSource(CensusOptions{Module: ModuleIdentity{Path: "example.com/dep"}, Files: map[string][]byte{"p.go": raw}})
			if err != nil {
				t.Fatal(err)
			}
			if c.Analysis.Complete || len(c.Obligations) == 0 {
				t.Fatalf("unsupported %s vanished", name)
			}
			for _, key := range c.Keys() {
				if len(c.Subjects(key).Blocking) == 0 {
					t.Fatal("unsupported propagation failed to block resource candidates")
				}
			}
		})
	}
}

func TestCensusAccountsForImplementationMaterial(t *testing.T) {
	for _, name := range []string{"native.s", "native.c", "input.proto", "nested/go.mod", "build_linux.go", "generated.go"} {
		t.Run(name, func(t *testing.T) {
			raw := []byte("opaque")
			if strings.HasSuffix(name, ".go") {
				raw = []byte("// Code generated by tool; DO NOT EDIT.\npackage p\n")
			}
			c, err := CensusSource(CensusOptions{Module: ModuleIdentity{Path: "example.com/dep"}, Files: map[string][]byte{"p.go": []byte("package p\n"), name: raw}})
			if err != nil {
				t.Fatal(err)
			}
			if c.Analysis.Complete {
				t.Fatal("unsupported material did not block")
			}
		})
	}
}
