// ActResearchCVE performs autonomous research and synthesizes the technical justification.
func ActResearchCVE(ctx context.Context, c *domain.AnalysisCase, resolver cveanalysis.SourceResolver, client llm.Completer) error {
	if c.CVEAnalysisProfile == domain.ProfileOff || c.CVEAnalysisProfile == "" {
		return nil
	}

	if resolver != nil {
		bundle, err := resolver.Resolve(ctx, c)
		if err == nil {
			c.CVEAnalysisBundle = &bundle
		}
	}

	if isNilClient(client) {
		if c.StrictLLM {
			return fmt.Errorf("strict-llm: llm client is required for cve analysis")
		}
		dossier := justification.Build(c)
		c.Justification = &dossier
		return nil
	}

	runner := cveanalysis.NewToolRunner()
	researcher := llm.NewResearcher(client, runner, 8)
	proposal, err := researcher.Research(ctx, c)
	if err != nil {
		if c.StrictLLM {
			return fmt.Errorf("strict-llm: cve research failed: %w", err)
		}
	} else {
		bindCVEProposal(c, &proposal)
		c.CVEAnalysis = &proposal

		// Strategy planning
		planner := llm.NewStrategyPlanner(client)
		plan, perr := planner.Plan(ctx, c)
		if perr != nil {
			if c.StrictLLM {
				return fmt.Errorf("strict-llm: strategy planning failed: %w", perr)
			}
		} else {
			c.StrategyPlan = &plan
		}

		// Semantic mechanism review (Gate A2)
		reviewer := llm.NewMechanismReviewer(client)
		rev, rerr := reviewer.Review(ctx, c, proposal)
		if rerr != nil {
			if c.StrictLLM {
				return fmt.Errorf("strict-llm: mechanism review failed: %w", rerr)
			}
		} else {
			rev.Proposal = &domain.ProposalRef{
				Source:   domain.ProposalSourceCVEResearch,
				ID:       proposal.ID,
				Revision: proposal.Revision,
			}
			c.SemanticReview = &rev
			if c.CVEAnalysisProfile == domain.ProfileVerified && rev.Passed {
				c.AcceptLocusProposals = true
			}
		}
	}

	dossier := justification.Build(c)
	c.Justification = &dossier
	return nil
}

// bindCVEProposal assigns the controller-owned proposal identity:
// LLM-supplied id/revision/binding values are never authoritative.
// Identity is deterministic ("PROP-<advisory>", revision one above any
// already-persisted verification of the same proposal); the artifact
// binding comes from the resolved source bundle or the affected result,
// never from model output. Verification records claiming this exact
// revision are discarded first — they are regenerated by VerifySites
// from deterministic checks, so anything that arrived with the model's
// proposal cannot impersonate a check that never ran.
func bindCVEProposal(c *domain.AnalysisCase, p *domain.CVEAnalysisProposal) {
	p.ID = "PROP-" + c.Vulnerability.ID
	revision := 1
	for _, rec := range c.ProposalVerifications {
		if rec.Proposal.Source == domain.ProposalSourceCVEResearch &&
			rec.Proposal.ID == p.ID && rec.Proposal.Revision >= revision {
			revision = rec.Proposal.Revision + 1
		}
	}
	p.Revision = revision
	if c.CVEAnalysisBundle != nil {
		p.Binding = c.CVEAnalysisBundle.Binding
	}
	if p.Binding.AdvisoryID == "" {
		p.Binding.AdvisoryID = c.Vulnerability.ID
	}
	if p.Binding.Module == "" && c.Affected != nil {
		p.Binding.Module = c.Affected.SelectedModule
		if p.Binding.Module == "" {
			p.Binding.Module = c.Vulnerability.Module
		}
		p.Binding.ResolvedVersion = c.Affected.ResolvedVersion
	}
	c.DiscardProposalVerifications(domain.ProposalRef{
		Source:   domain.ProposalSourceCVEResearch,
		ID:       p.ID,
		Revision: p.Revision,
	})
	// Mechanism ids are positional and unique within the revision — the
	// model's own ids may collide or be empty.
	for i := range p.Mechanisms {
		p.Mechanisms[i].ID = fmt.Sprintf("M-%d", i+1)
	}
}

func isNilClient(c llm.Completer) bool {
	if c == nil {
		return true
	}
	if cl, ok := c.(*llm.Client); ok && cl == nil {
		return true
	}
	return false
}
